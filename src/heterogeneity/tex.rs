//! TeX eps-loader files of `heterogeneity_simulate` with the `tex` option (and
//! `graph_format=eps`): `+heterogeneity/plot_irfs.m` (`<fname>_IRF.tex`) and `plot_simulation.m`
//! (`<fname>_simulation.tex`, `<fname>_det_simulation.tex`).
use std::path::{Path, PathBuf};

use anyhow::Result;

use super::simulate::SimOptions;
use crate::model::Model;

/// `options_.figures.textwidth`.
const TEXTWIDTH: f64 = 0.8;

/// One `figure` entry; `caption_nl`: the caption line ends with a newline before `\label`.
fn figure(width: f64, base: &str, caption: &str, label: &str, caption_nl: bool) -> String {
    let nl = if caption_nl { "\n" } else { "" };
    format!(
        "\\begin{{figure}}[H]\n\\centering \n\\includegraphics[width={width:.2}\\textwidth]{{{base}}}\n\\caption{{{caption}}}{nl}\\label{{{label}}}\n\\end{{figure}}\n \n"
    )
}

/// Figure entries of `n` panels: `(suffix of the file name, width, label suffix)` per figure.
fn layout(n: usize) -> Vec<(String, f64, String)> {
    let (nbplt, _nr, nc, lr, lc, nstar) = crate::analysis::irf::pltorg(n);
    let mut v = Vec::new();
    if nbplt == 1 {
        v.push((String::new(), TEXTWIDTH * (n as f64 / nc as f64).min(1.0), String::new()));
    } else if nbplt > 1 {
        for f in 1..nbplt {
            v.push((f.to_string(), TEXTWIDTH * (nstar as f64 / nc as f64).min(1.0), format!(":{f}")));
        }
        let m = n - (nbplt - 1) * nstar;
        let c = if lr > 0 { lc } else { nc };
        v.push((nbplt.to_string(), TEXTWIDTH * (m as f64 / c as f64).min(1.0), format!(":{nbplt}")));
    }
    v
}

fn write(dir: &Path, fname: &str, file: &str, body: String) -> Result<PathBuf> {
    let s = format!("{body} \n% End Of TeX file. \n");
    let d = crate::graphics::graph_dir(dir, fname);
    std::fs::create_dir_all(&d)?;
    let p = d.join(file);
    std::fs::write(&p, s)?;
    Ok(p)
}

/// `<fname>_IRF.tex`; `shock_tex[k]` is `M_.exo_names_tex{k}`.
pub fn write_irf_tex(
    model: &Model,
    shock_tex: &[String],
    irfs: &[(String, Vec<f64>)],
    opts: &SimOptions,
    dir: &Path,
    fname: &str,
) -> Result<PathBuf> {
    let thr = opts.irf_plot_threshold.unwrap_or(1e-10);
    let what = if opts.relative_irf.unwrap_or(false) {
        "Relative impulse response functions"
    } else {
        "Impulse response functions"
    };
    let mut s = format!(
        "% TeX eps-loader file generated by heterogeneity.plot_irfs (Dynare).\n% {}\n \n",
        crate::latex::datestr_now()
    );
    let base = format!("{fname}/graphs/{fname}");
    // shocks in the order of the IRF list (shock_list)
    let mut order: Vec<usize> = Vec::new();
    for (n, _) in irfs {
        if let Some(k) = model.exo_names.iter().position(|e| n.ends_with(&format!("_{e}"))) {
            if !order.contains(&k) {
                order.push(k);
            }
        }
    }
    for k in order {
        let sname = &model.exo_names[k];
        let suffix = format!("_{sname}");
        let n = irfs
            .iter()
            .filter(|(nm, v)| nm.ends_with(&suffix) && v.iter().fold(0.0f64, |m, x| m.max(x.abs())) >= thr)
            .count();
        let cap = format!("{what} (orthogonalized shock to ${}$).", shock_tex[k]);
        let single = n > 0 && crate::analysis::irf::pltorg(n).0 == 1;
        for (file, w, lab) in layout(n) {
            s += &figure(w, &format!("{base}_IRF_{sname}{file}"), &cap, &format!("Fig:IRF:{sname}{lab}"), single);
        }
    }
    write(dir, fname, &format!("{fname}_IRF.tex"), s)
}

/// `<fname>_simulation.tex` / `<fname>_det_simulation.tex`.
pub fn write_simulation_tex(
    model: &Model,
    var_list: &[String],
    news: bool,
    dir: &Path,
    fname: &str,
) -> Result<PathBuf> {
    let (suffix, caption, label) = if news {
        ("_det_simulation", "Deterministic shock sequence.", "det_simulation")
    } else {
        ("_simulation", "Stochastic simulation.", "simulation")
    };
    let nv = if var_list.is_empty() { model.endo_names.len() } else { var_list.len() };
    let mut s = format!(
        "% TeX eps-loader file generated by heterogeneity.plot_time_series (Dynare).\n% {}\n \n",
        crate::latex::datestr_now()
    );
    let base = format!("{fname}/graphs/{fname}{suffix}");
    for (file, w, lab) in layout(nv) {
        s += &figure(w, &format!("{base}{file}"), caption, &format!("Fig:{label}{lab}"), true);
    }
    write(dir, fname, &format!("{fname}{suffix}.tex"), s)
}
